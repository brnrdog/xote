#!/usr/bin/env node
/**
 * Generates src/SearchIndex.res: every docs page plus its h2–h4 headings, so
 * the search palette can jump straight to a section. Heading ids are made with
 * the same slugger rehype-slug uses, so they match the anchors on the page.
 *
 * Usage: node scripts/generate-search-index.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import GithubSlugger from 'github-slugger'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const docsDir = path.join(__dirname, '..', 'src', 'docs')
const outputPath = path.join(__dirname, '..', 'src', 'SearchIndex.res')

// Search order: pages appear in this order when the query is empty.
const pages = [
  ['Introduction', '/docs', 'Getting Started', 'IntroDoc'],
  ['Learning ReScript', '/docs/getting-started/rescript', 'Getting Started', 'LearningReScriptDoc'],
  ['JavaScript Runtime', '/docs/getting-started/javascript-typescript', 'Getting Started', 'JavaScriptTypeScriptDoc'],
  ['Signals', '/docs/core-concepts/signals', 'Core Modules', 'SignalsDoc'],
  ['Computeds', '/docs/core-concepts/computed', 'Core Modules', 'ComputedDoc'],
  ['Effects', '/docs/core-concepts/effects', 'Core Modules', 'EffectsDoc'],
  ['View', '/docs/view/overview', 'Core Modules', 'ViewsDoc'],
  ['Context', '/docs/core-concepts/context', 'Core Modules', 'ContextDoc'],
  ['Resources', '/docs/core-concepts/resources', 'Core Modules', 'ResourcesDoc'],
  ['Router', '/docs/router/overview', 'Router', 'RouterDoc'],
  ['Signal API', '/docs/api/signal', 'API Reference', 'ApiSignalDoc'],
  ['Computed API', '/docs/api/computed', 'API Reference', 'ApiComputedDoc'],
  ['Effect API', '/docs/api/effect', 'API Reference', 'ApiEffectDoc'],
  ['View API', '/docs/api/view', 'API Reference', 'ApiViewDoc'],
  ['React Comparison', '/docs/comparisons/react', 'Comparisons', 'ReactComparisonDoc'],
  ['SolidJS Comparison', '/docs/comparisons/solidjs', 'Comparisons', 'SolidJSComparisonDoc'],
  ['Server-Side Rendering', '/docs/advanced/ssr', 'Advanced', 'SSRDoc'],
  ['MDX Support', '/docs/advanced/mdx-support', 'Advanced', 'MdxDoc'],
  ['Batching', '/docs/advanced/batching', 'Advanced', 'BatchingDoc'],
  ['Technical Overview', '/docs/technical-overview', 'Advanced', 'TechnicalOverviewDoc'],
  ['Changelog', '/docs/changelog', 'Project', null],
]

// Plain text of a Markdown heading, the way rehype-slug sees it.
function headingText(markdown) {
  return markdown
    .replace(/`([^`]*)`/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/(\*\*|__|\*|_)(.*?)\1/g, '$2')
    .trim()
}

function headingsOf(file) {
  if (!file) return []
  const source = fs.readFileSync(path.join(docsDir, `${file}.mdx`), 'utf-8')
  const slugger = new GithubSlugger()
  const headings = []
  let inFence = false
  for (const line of source.split('\n')) {
    if (/^\s*```/.test(line)) inFence = !inFence
    if (inFence) continue
    const match = /^(#{1,6})\s+(.+?)\s*#*\s*$/.exec(line)
    if (!match) continue
    const text = headingText(match[2])
    const id = slugger.slug(text)
    const level = match[1].length
    if (level >= 2 && level <= 4) headings.push({ text, id, level })
  }
  return headings
}

const str = value => JSON.stringify(value)

const body = pages
  .map(([title, pagePath, section, file]) => {
    const headings = headingsOf(file)
      .map(h => `      {text: ${str(h.text)}, id: ${str(h.id)}, level: ${h.level}},`)
      .join('\n')
    return `  {
    title: ${str(title)},
    path: ${str(pagePath)},
    section: ${str(section)},
    headings: [
${headings}
    ],
  },`
  })
  .join('\n')

const output = `// Generated by scripts/generate-search-index.mjs from the MDX docs. Do not edit.

type heading = {text: string, id: string, level: int}

type page = {
  title: string,
  path: string,
  section: string,
  headings: array<heading>,
}

let pages: array<page> = [
${body}
]
`

fs.writeFileSync(outputPath, output)
console.log(`Generated ${path.relative(process.cwd(), outputPath)} (${pages.length} pages)`)
